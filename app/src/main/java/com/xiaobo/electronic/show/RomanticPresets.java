    /** 取某一套文案的首句摘要，用于列表预览 */
    public static String summary(String preset) {
        String[] lines = preset.split("\n");
        String first = lines.length > 0 ? lines[0] : preset;
        if (first.length() > 12) first = first.substring(0, 12) + "…";
        return first + "  （共 " + lines.length + " 句）";
    }
